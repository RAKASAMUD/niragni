// ---------------------------------------------------------------------------
// Optional localStorage persistence, namespaced to the preview. Falls back to
// pure in-memory if storage is unavailable (SSR/private mode).
// ---------------------------------------------------------------------------
const STORAGE_KEY = 'niragni-web-preview-demo-reports-v1';

function loadReports(): Report[] {
  try {
    const raw = typeof localStorage !== 'undefined' ? localStorage.getItem(STORAGE_KEY) : null;
    if (raw) {
      const parsed = JSON.parse(raw) as Report[];
      if (Array.isArray(parsed)) return parsed;
    }
  } catch {
    /* ignore corrupt/unavailable storage */
  }
  return seedReports();
}

function persist(reports: Report[]): void {
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(reports));
    }
  } catch {
    /* ignore quota/unavailable storage */
  }
}

function clone<T>(v: T): T {
  return JSON.parse(JSON.stringify(v)) as T;
}

function genId(): string {
  return `demo-report-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

