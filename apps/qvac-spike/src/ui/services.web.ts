/**
 * WEB-ONLY DEMO service boundary (UI PREVIEW).
 *
 * Metro/Expo resolves `.web.ts` ahead of `.ts` on the web platform, so on web
 * the UI imports THIS module instead of `./services.ts`. That keeps the native
 * production implementation (`../core/index` → QVAC/BareKit, expo-sqlite,
 * expo-file-system, expo-image-picker, react-native-share, …) OUT of the web
 * bundle's import graph entirely. This is a platform-resolution boundary, not a
 * `Platform.OS` runtime gate — the native modules are never imported here.
 *
 * ============================= IMPORTANT =============================
 * This is DEMO / UI PREVIEW data for coordinator review in a browser. It is
 * NOT the real app behaviour:
 *   - All reports/channels below are fabricated DEMO fixtures.
 *   - The AI "suggestion" is explicitly-labelled PERSISTENT DEMO EXAMPLE TEXT.
 *     It is NOT generated by any model, NOT produced offline, and carries NO
 *     real latency. Nothing here ever claims "Siap offline", runs inference,
 *     or reports a measured duration from a real run.
 *   - Native-only actions (download/import/check a model, add a camera/library
 *     photo, share, copy, open dialer) return honest "not available in the web
 *     preview" states instead of pretending to work.
 * Persistence (optional) uses the browser's localStorage, namespaced to this
 * preview only, so a coordinator's edits survive a page reload during review.
 * =====================================================================
 */
