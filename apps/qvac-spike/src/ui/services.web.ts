function demoPhotoUri(label: string, bg: string): string {
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="320" height="320">` +
    `<rect width="320" height="320" fill="${bg}"/>` +
    `<text x="160" y="150" font-family="sans-serif" font-size="22" fill="#fff" text-anchor="middle">CONTOH DEMO</text>` +
    `<text x="160" y="185" font-family="sans-serif" font-size="16" fill="#fff" text-anchor="middle">${label}</text>` +
    `</svg>`;
  // encodeURIComponent keeps it valid as a data URI across browsers.
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

